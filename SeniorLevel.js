// 2️⃣ Execution Context & Event Loop
// •	Execution Context: Environment where JS code is executed.
// o	Global Execution Context (GEC) – created when the JS program starts.
// o	Function Execution Context (FEC) – created each time a function is invoked.
// •	Phases:
// 1.	Creation Phase → Memory allocation for variables and functions.
// 2.	Execution Phase → Code runs line by line.
// •	Event Loop: Handles asynchronous code (like setTimeout, fetch).
// o	Moves tasks from the callback queue to the call stack once it’s empty.
// 🧩 Example:
// console.log("1");
// setTimeout(() => console.log("2"), 0);
// console.log("3");
// Output: 1, 3, 2
