// 2. How React manages the Virtual DOM and its benefits
// •	Virtual DOM (VDOM) is an in-memory representation of the actual DOM. React maintains this virtual tree of elements.
// •	How it works:
// 1.	Component renders → React creates a virtual DOM tree.
// 2.	On state or props change → a new VDOM tree is generated.
// 3.	React diffs the new tree against the previous VDOM tree.
// 4.	Only the minimal set of changes are applied to the real DOM.
