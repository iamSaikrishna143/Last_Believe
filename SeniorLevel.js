// 25️⃣ What is the React Reconciliation Process?
// Reconciliation is React’s diffing algorithm that determines how the Virtual DOM and Real DOM should sync after a change.
// Steps:
// 1.	React creates a new Virtual DOM tree after state/prop change.
// 2.	Compares (diffs) new tree with the old one.
// 3.	Finds minimal differences.
// 4.	Updates only changed elements in the Real DOM.
// ✅ Key Concept: “React Fiber” — an optimized reconciliation algorithm for smoother rendering.
// ________________________________________
// 26️⃣ How React Compares Virtual DOM with Real DOM
// Step	Description
// 1️⃣ Create Virtual DOM	React builds an in-memory tree of components
// 2️⃣ Diff Algorithm	Compares new Virtual DOM with previous one
// 3️⃣ Minimal Updates	Only changes are applied to the Real DOM (batch updates)
// 4️⃣ Commit Phase	Real DOM is updated efficiently
// 🧩 Example:
// Changing one list item → React only updates that node, not the entire list.
